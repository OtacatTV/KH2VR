"""Turn the probe's PADREC lines (pad_record=1, the physical pad) into a pad script for the test driver.

  pad_from_log.py <kh2vr_probe.log> <out.pad> [--after HH:MM:SS] [--before HH:MM:SS] [--tail-ms 500]

Takes the recorded states between the first non-neutral state after --after and the last change before
--before; each state lasts until the next change. Leading idle time is dropped, a neutral --tail-ms ends
the script. Prints step count and total duration. Replays are open loop: check where they end up
(screen state, measured position) before trusting them.
"""
import argparse
import re
import sys

NAMES = [(0x1, "UP"), (0x2, "DOWN"), (0x4, "LEFT"), (0x8, "RIGHT"), (0x10, "START"), (0x20, "BACK"), (0x40, "LS"),
         (0x80, "RS"), (0x100, "LB"), (0x200, "RB"), (0x1000, "A"), (0x2000, "B"), (0x4000, "X"), (0x8000, "Y")]
RX = re.compile(r"^(\d\d:\d\d:\d\d)\.\d+ PADREC (\d+) 0x([0-9a-f]{4}) (\S+) (\S+) (\S+) (\S+) (\S+) (\S+)")


def buttons(mask):
    names = [n for b, n in NAMES if mask & b]
    return "+".join(names) if names else "-"


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("log")
    ap.add_argument("out")
    ap.add_argument("--after", default="00:00:00")
    ap.add_argument("--before", default="99:99:99")
    ap.add_argument("--tail-ms", type=float, default=500)
    a = ap.parse_args(argv)
    recs = []
    for line in open(a.log, encoding="utf-8", errors="replace"):
        m = RX.match(line)
        if not m or not (a.after <= m.group(1) <= a.before):
            continue
        vals = [float(x) for x in m.groups()[3:]]
        recs.append((float(m.group(2)), int(m.group(3), 16), vals))
    while recs and recs[0][1] == 0 and not any(recs[0][2]):
        recs.pop(0)
    if not recs:
        print("ERROR no non-neutral PADREC lines in range")
        return 2
    lines = ["# Generated by pad_from_log.py from %s (%s..%s)" % (a.log, a.after, a.before)]
    total = 0.0
    for i, (t, b, v) in enumerate(recs):
        dur = (recs[i + 1][0] - t) if i + 1 < len(recs) else a.tail_ms
        if dur <= 0:
            continue
        axes = " ".join("%.2f" % x for x in v)
        lines.append("%.0f %s %s" % (dur, buttons(b), axes))
        total += dur
    if recs[-1][1] or any(recs[-1][2]):
        lines.append("%.0f -" % a.tail_ms)
        total += a.tail_ms
    open(a.out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("OK %d steps, %.1f s -> %s" % (len(lines) - 1, total / 1000, a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
